    <li>сломались или ослабились лепестки диафрагменной пружины;</li>
    <li>подшипник выключения сцепления вышел из строя;</li>
    <li>сработалась поверхность маховика;</li>
    <li>трещина или износ нажимного диска;</li>
    <li>заедание и закусывание вилки выключения сцепления;</li>
    <li>разрыв троса в механическом приводе;</li>
    <li>засорение или утечка жидкости в гидравлическом приводе;</li>
</ol>

